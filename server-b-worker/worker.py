# Helpers
# ---------------------------------------------------------------------------

def _is_market_hours() -> bool:
    """Check if US stock markets are currently open (9:30 AM – 4:00 PM ET, Mon–Fri).

    Uses a simplified check without holiday awareness.  The worker runs more
    frequently during these hours since news volume is highest.

    Returns:
        True if the current time falls within US market hours.
    """
    now_utc = datetime.now(timezone.utc)
    # US Eastern is UTC-5 (EST) or UTC-4 (EDT).  Use UTC-4 as a conservative
    # approximation (market hours effectively 13:30–20:00 UTC during EDT).
    hour_utc = now_utc.hour
    weekday = now_utc.weekday()  # 0=Monday, 6=Sunday

    # Skip weekends.
    if weekday >= 5:
        return False

    # Approximate EDT market hours: 13:30 – 20:00 UTC.
    if 13 <= hour_utc < 20:
        return True
    return False


def _score_with_ollama(title: str, summary: str) -> dict:
    """Call the local Ollama API to score a news article with the LLM.

    Builds a prompt from the article headline and summary (plus any learned
    calibration rules), sends it to the Ollama ``/api/generate`` endpoint,
    and parses the JSON response.

    Args:
        title:   Article headline text.
        summary: Article summary text (may be empty/None).

    Returns:
        Parsed dict with keys: general_score, general_reasoning, tickers.

    Raises:
        ValueError: If the LLM response cannot be parsed as valid JSON.
        requests.RequestException: On network/connection errors.
    """
    # Build the prompt with optional learned rules injection.
    prompt = _build_prompt(title, summary)

    payload = {
        "model": OLLAMA_MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": 0.1,   # Low temperature for deterministic scoring
            "num_predict": 512,   # Cap output length
        },
    }

    resp = requests.post(
        f"{OLLAMA_URL}/api/generate",
        json=payload,
        timeout=_OLLAMA_TIMEOUT,
    )
    resp.raise_for_status()

    raw_text = resp.json().get("response", "")

    # Attempt to extract JSON from the LLM output.  The model may wrap it
    # in markdown code fences or include preamble text.
    return _parse_llm_json(raw_text)


def _parse_llm_json(raw_text: str) -> dict:
    """Extract and parse a JSON object from raw LLM output.

    Handles common LLM quirks: markdown code fences, trailing commas,
    preamble text before the JSON block.

    Args:
        raw_text: Raw text response from the LLM.

    Returns:
        Parsed dict with validated structure.

    Raises:
        ValueError: If no valid JSON can be extracted.
    """
    text = raw_text.strip()

    # Strip markdown code fences if present.
    fence_match = re.search(r"```(?:json)?\s*\n?(.*?)\n?```", text, re.DOTALL)
    if fence_match:
        text = fence_match.group(1).strip()

    # Try to find a JSON object in the text.
    # Look for the outermost { ... } block.
    brace_start = text.find("{")
    if brace_start == -1:
        raise ValueError(f"No JSON object found in LLM response: {raw_text[:200]}")

    # Find the matching closing brace.
    depth = 0
    brace_end = -1
    for i in range(brace_start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                brace_end = i
                break

    if brace_end == -1:
        raise ValueError(f"Unmatched braces in LLM response: {raw_text[:200]}")

    json_str = text[brace_start : brace_end + 1]

    # Remove trailing commas before } or ] (common LLM mistake).
    json_str = re.sub(r",\s*([}\]])", r"\1", json_str)

    try:
        data = json.loads(json_str)
    except json.JSONDecodeError as e:
        raise ValueError(
            f"Invalid JSON from LLM: {e}. Raw: {json_str[:200]}"
        ) from e

    # Validate and clamp the structure.
    return _validate_score(data)


def _validate_score(data: dict) -> dict:
    """Validate and sanitise the parsed LLM scoring output.

    Ensures scores are clamped to [-5, +5] and the structure matches what
    Server A's ingestion endpoint expects.

    Args:
        data: Parsed JSON dict from the LLM.

    Returns:
        Validated dict with correct types and ranges.
    """
    general_score = data.get("general_score", 0)
    if not isinstance(general_score, (int, float)):
        general_score = 0
    general_score = max(-5, min(5, int(general_score)))

    general_reasoning = data.get("general_reasoning", "")
    if not isinstance(general_reasoning, str):
        general_reasoning = ""

    tickers = []
    raw_tickers = data.get("tickers", [])
    if isinstance(raw_tickers, list):
        for t in raw_tickers:
            if not isinstance(t, dict):
                continue
            symbol = t.get("symbol", "").strip().upper()
            if not symbol or len(symbol) > 10:
                continue
            score = t.get("score", 0)
            if not isinstance(score, (int, float)):
                score = 0
            score = max(-5, min(5, int(score)))
            reasoning = t.get("reasoning", "")
            if not isinstance(reasoning, str):
                reasoning = ""
            tickers.append({
                "ticker": symbol,
                "score": score,
                "reasoning": reasoning[:500],  # Cap reasoning length
            })

    return {
        "general_score": general_score,
        "general_reasoning": general_reasoning[:500],
        "tickers": tickers,
    }


def _build_ingest_payload(article: dict, scores: dict) -> dict:
    """Combine a raw article dict with LLM scores into an ingestion payload.

    The payload matches the ``NewsArticleIngest`` schema expected by
    Server A's ``POST /api/v1/news/internal/news`` endpoint.

    Args:
        article: Article dict from sources.py (title, url, source, etc.).
        scores:  Validated LLM scoring dict (general_score, tickers, etc.).

    Returns:
        Dict ready to be JSON-serialised and POSTed to Server A.
    """
    return {
        "url": article["url"],
        "title": article["title"],
        "summary": article.get("summary"),
        "source": article["source"],
        "published_at": article.get("published_at"),
        "general_score": scores["general_score"],
        "general_reasoning": scores["general_reasoning"],
        "tickers": scores["tickers"],
    }


def _post_to_server_a(payloads: list) -> bool:
    """POST a batch of scored articles to Server A's ingestion endpoint.

    Args:
        payloads: List of article dicts matching NewsArticleIngest schema.

    Returns:
        True if the POST succeeded (2xx), False otherwise.
    """
    if not payloads:
        return True

    headers = {
        "Content-Type": "application/json",
        "X-Internal-Key": INTERNAL_KEY,
    }

    try:
        resp = requests.post(
            _INGEST_ENDPOINT,
            json=payloads,
            headers=headers,
            timeout=30,
        )
        if resp.ok:
            result = resp.json()
            logger.info(
                "Posted %d articles to Server A: inserted=%s, skipped=%s",
                len(payloads),
                result.get("inserted"),
                result.get("skipped"),
            )
            return True
        else:
            logger.error(
                "Server A rejected POST: status=%d, body=%s",
                resp.status_code,
                resp.text[:300],
            )
            return False
    except requests.RequestException as exc:
        logger.error("Failed to POST to Server A: %s", exc)
        return False


# ---------------------------------------------------------------------------
# Queue flush
# ---------------------------------------------------------------------------

def _flush_queue() -> None:
    """Attempt to deliver all pending articles from the local SQLite queue.

    Retrieves queued payloads, POSTs each individually to Server A, and
    updates the queue accordingly (mark done on success, increment retries
    on failure).
    """
    pending = article_queue.get_pending(limit=50)
    if not pending:
        return

    logger.info("Flushing %d pending articles from local queue...", len(pending))

    for row_id, payload_json in pending:
        try:
            payloads = json.loads(payload_json)
            # Ensure it's a list (single-article payloads are wrapped).
            if isinstance(payloads, dict):
                payloads = [payloads]

            success = _post_to_server_a(payloads)
            if success:
                article_queue.mark_done(row_id)
            else:
                article_queue.increment_retries(row_id)
        except Exception as exc:
            logger.error("Queue flush error for row %d: %s", row_id, exc)
            article_queue.increment_retries(row_id)


# ---------------------------------------------------------------------------
# Main cycle
# ---------------------------------------------------------------------------

def _run_cycle() -> None:
    """Execute one complete worker cycle: rules refresh → flush → fetch → score → post.

    This is the core business logic called repeatedly from the main loop.
    """
    global _seen_urls

    # 0. Refresh learned scoring rules from Server A (every N cycles).
    _maybe_refresh_rules()

    # 1. Flush any pending articles from the local queue first.
    _flush_queue()

    # 2. Fetch news from all sources.
    logger.info("Fetching news from all sources...")
    raw_articles = sources.fetch_all_news()
    logger.info("Fetched %d unique articles from sources.", len(raw_articles))

    if not raw_articles:
        logger.info("No articles fetched this cycle.")
        return

    # 3. Deduplicate against already-seen URLs (in-memory + Server A dedup).
    new_articles = []
    for article in raw_articles:
        url = article.get("url", "")
        if url and url not in _seen_urls:
            new_articles.append(article)
            _seen_urls.add(url)

    # Cap the seen set to prevent unbounded memory growth.
    if len(_seen_urls) > _MAX_SEEN_URLS:
        # Keep the most recent half.
        _seen_urls = set(list(_seen_urls)[_MAX_SEEN_URLS // 2 :])

    if not new_articles:
        logger.info("No new articles after dedup.")
        return

    # Limit to MAX_ARTICLES_PER_CYCLE to avoid overloading Ollama.
    articles_to_process = new_articles[:_MAX_ARTICLES_PER_CYCLE]
    logger.info(
        "Processing %d new articles (skipped %d already seen).",
        len(articles_to_process),
        len(raw_articles) - len(new_articles),
    )

    # 4. Score each article with the LLM and build ingestion payloads.
    scored_payloads = []
    for i, article in enumerate(articles_to_process, 1):
        title = article.get("title", "Untitled")
        logger.info(
            "[%d/%d] Scoring: %.80s",
            i,
            len(articles_to_process),
            title,
        )
        try:
            scores = _score_with_ollama(title, article.get("summary"))
            payload = _build_ingest_payload(article, scores)
            scored_payloads.append(payload)
        except ValueError as exc:
            logger.warning("LLM parse error for '%.60s': %s", title, exc)
            # Assign a neutral score rather than dropping the article entirely.
            payload = _build_ingest_payload(article, {
                "general_score": 0,
                "general_reasoning": "Unable to score — LLM parse failure.",
                "tickers": [],
            })
            scored_payloads.append(payload)
        except requests.RequestException as exc:
            logger.error("Ollama connection error for '%.60s': %s", title, exc)
            # Don't add to scored_payloads — can't score without the LLM.
            continue

    if not scored_payloads:
        logger.info("No articles scored this cycle.")
        return

    # 5. POST scored articles to Server A in batches.
    for batch_start in range(0, len(scored_payloads), _POST_BATCH_SIZE):
        batch = scored_payloads[batch_start : batch_start + _POST_BATCH_SIZE]
        success = _post_to_server_a(batch)
        if not success:
            # Queue each article individually for retry.
            for payload in batch:
                article_queue.enqueue(json.dumps(payload))
            logger.warning(
                "Queued %d articles locally (Server A unreachable).", len(batch)
            )


# ---------------------------------------------------------------------------
# Main loop
# ---------------------------------------------------------------------------

def main() -> None:
    """Entry point: initialise the queue DB and run the worker loop forever.

    The loop runs one cycle, then sleeps for 10 minutes during US market
    hours or 30 minutes during off-hours.  Any unhandled exception in a
    cycle is caught and logged so the worker doesn't crash.
    """
    logger.info("=" * 60)
    logger.info("TickerTap News Worker starting")
    logger.info("  Server A URL:  %s", API_URL)
    logger.info("  Ollama URL:    %s", OLLAMA_URL)
    logger.info("  Ollama model:  %s", OLLAMA_MODEL)
    logger.info("  Internal key:  %s", "SET" if INTERNAL_KEY else "NOT SET")
    logger.info("  Rules refresh: every %d cycles", _RULES_REFRESH_EVERY)
    logger.info("=" * 60)

    if not INTERNAL_KEY:
        logger.warning(
            "TICKERTAP_INTERNAL_KEY is not set! "
            "POSTs to Server A will be rejected."
        )

    # Initialise the local SQLite queue.
    article_queue.init_db()

    cycle_count = 0
    while True:
        cycle_count += 1
        logger.info("--- Cycle %d starting ---", cycle_count)

        try:
            _run_cycle()
        except Exception:
            logger.exception("Unhandled error in worker cycle %d.", cycle_count)

        # Determine sleep interval.
        if _is_market_hours():
            sleep_secs = _SLEEP_MARKET_HOURS
            logger.info(
                "Market hours — sleeping %d minutes. Pending queue: %d",
                sleep_secs // 60,
                article_queue.pending_count(),
            )
        else:
            sleep_secs = _SLEEP_OFF_HOURS
            logger.info(
                "Off-hours — sleeping %d minutes. Pending queue: %d",
                sleep_secs // 60,
                article_queue.pending_count(),
            )

        time.sleep(sleep_secs)


if __name__ == "__main__":
    main()
