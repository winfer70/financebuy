"""
worker.py — TickerTap background news worker for Server B (REDACTED_HOST).

Main loop:
    1. Flush any pending articles from the local SQLite queue.
    2. Optionally refresh learned scoring rules from Server A.
    3. Fetch news from all 4 sources (Yahoo, Google, Finviz, MarketWatch).
    4. Deduplicate against already-seen URLs (local in-memory set).
    5. For each new article:
       a. Build an LLM prompt with headline + summary + learned rules.
       b. Call the local Ollama API (http://localhost:11434/api/generate).
       c. Parse the structured JSON response.
       d. POST scored article to Server A's internal ingestion endpoint.
       e. On failure → queue to local SQLite for retry.
    6. Sleep (10 min during US market hours, 30 min off-hours).

The worker periodically fetches calibration rules generated by the learner
(learner.py) from Server A.  These rules are injected into the LLM prompt
to improve scoring accuracy over time (AppREDACTED 2 — dynamic system prompt).

Environment variables (set via systemd or .env):
    TICKERTAP_API_URL      — Server A base URL (e.g. http://<APP_IP>:8000)
    TICKERTAP_INTERNAL_KEY — Shared secret for the X-Internal-Key header
    OLLAMA_MODEL           — Ollama model tag (default: llama3:8b-instruct-q4_K_M)
    OLLAMA_URL             — Ollama API base URL (default: http://localhost:11434)

Usage:
    python worker.py
"""

import json
import logging
import os
import re
import sys
import time
from datetime import datetime, timezone
from typing import Optional

import requests

import article_queue
import sources

# ---------------------------------------------------------------------------
# Logging configuration
# ---------------------------------------------------------------------------
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    datefmt="%Y-%m-%d %H:%M:%S",
    handlers=[logging.StreamHandler(sys.stdout)],
)
logger = logging.getLogger("tickertap-worker")

# ---------------------------------------------------------------------------
# Configuration from environment
# ---------------------------------------------------------------------------
API_URL = os.getenv("TICKERTAP_API_URL", "http://localhost:8000")
INTERNAL_KEY = os.getenv("TICKERTAP_INTERNAL_KEY", "")
OLLAMA_MODEL = os.getenv("OLLAMA_MODEL", "llama3:8b-instruct-q4_K_M")
OLLAMA_URL = os.getenv("OLLAMA_URL", "http://localhost:11434")

# Internal ingestion endpoint on Server A.
_INGEST_ENDPOINT = f"{API_URL}/api/v1/news/internal/news"

# Active scoring rules endpoint on Server A (feedback loop).
_RULES_ENDPOINT = f"{API_URL}/api/v1/feedback/internal/rules/active"

# How often to refresh learned scoring rules (every N cycles).
# At 10-min cycles during market hours this is roughly every hour.
_RULES_REFRESH_EVERY = 6

# Sleep intervals in seconds.
_SLEEP_MARKET_HOURS = 600    # 10 minutes
_SLEEP_OFF_HOURS = 1800      # 30 minutes

# Batch size for POSTing to Server A (send in chunks to avoid huge payloads).
_POST_BATCH_SIZE = 10

# Maximum articles to process per cycle to avoid overloading Ollama.
_MAX_ARTICLES_PER_CYCLE = 50

# Ollama generation timeout (LLM can be slow on large prompts).
_OLLAMA_TIMEOUT = 120  # seconds


# ---------------------------------------------------------------------------
# LLM Prompt — base template + dynamic rules injection
# ---------------------------------------------------------------------------

# Base scoring instructions (always included).
_LLM_PROMPT_BASE = """You are a financial news analyst. Analyze this news article and return ONLY valid JSON.

Article headline: {title}
Article summary: {summary}

Return this exact JSON structure:
{{
  "general_score": <integer -5 to +5, where -5 is extremely bearish and +5 is extremely bullish for the overall market>,
  "general_reasoning": "<one sentence explaining the general market impact>",
  "tickers": [
    {{
      "symbol": "<affected stock ticker>",
      "score": <integer -5 to +5 for this specific stock>,
      "reasoning": "<one sentence explaining impact on this stock>"
    }}
  ]
}}

Rules:
- Only include tickers that are directly or significantly affected
- Score 0 means neutral/no impact
- Keep reasoning concise (one sentence max)
- Return valid JSON only, no markdown or explanation"""

# Template for injecting learned calibration rules above the base prompt.
_RULES_SECTION_TEMPLATE = """=== LEARNED SCORING RULES ===
Based on analysis of past prediction accuracy, apply these calibration rules:
{rules_text}
=== END RULES ===

"""


# ---------------------------------------------------------------------------
# Learned rules state (refreshed every _RULES_REFRESH_EVERY cycles)
# ---------------------------------------------------------------------------

# Cached rules text from Server A (None = never fetched, "" = no active rules).
_cached_rules_text: Optional[str] = None

# Cycle counter for rules refresh (fetches on first cycle, then every N).
_rules_refresh_counter: int = 0


def _fetch_active_rules() -> Optional[str]:
    """Fetch the currently active scoring rules from Server A.

    Calls ``GET /api/v1/feedback/internal/rules/active`` and extracts the
    ``rules_text`` field.  Returns None if no active rules exist or on error.

    Returns:
        The active rules text string, or None if unavailable.
    """
    headers = {"X-Internal-Key": INTERNAL_KEY}
    try:
        resp = requests.get(_RULES_ENDPOINT, headers=headers, timeout=10)
        if resp.status_code == 404:
            # No active rules yet — this is normal before the learner runs.
            logger.info("No active scoring rules on Server A (404).")
            return None
        if resp.status_code != 200:
            logger.warning(
                "Failed to fetch scoring rules: status=%d", resp.status_code
            )
            return None
        rules_text = resp.json().get("rules_text", "")
        if rules_text:
            logger.info(
                "Fetched active scoring rules (v%s, %d chars).",
                resp.json().get("rule_version", "?"),
                len(rules_text),
            )
        return rules_text or None
    except requests.RequestException as exc:
        logger.warning("Could not reach Server A for scoring rules: %s", exc)
        return None


def _maybe_refresh_rules() -> None:
    """Refresh cached scoring rules if the refresh interval has elapsed.

    Called at the start of each worker cycle.  Fetches new rules from
    Server A every ``_RULES_REFRESH_EVERY`` cycles to pick up learner
    updates without hammering the API.
    """
    global _cached_rules_text, _rules_refresh_counter

    _rules_refresh_counter += 1
    if _rules_refresh_counter >= _RULES_REFRESH_EVERY or _cached_rules_text is None:
        _cached_rules_text = _fetch_active_rules()
        _rules_refresh_counter = 0


def _build_prompt(title: str, summary: str) -> str:
    """Build the full LLM scoring prompt, optionally injecting learned rules.

    If the worker has cached scoring rules from the learner, they are
    prepended as a calibration section before the base scoring instructions.

    Args:
        title:   Article headline text.
        summary: Article summary text (may be empty/None).

    Returns:
        Formatted prompt string ready for the Ollama API.
    """
    parts = []

    # Inject learned rules section if available.
    if _cached_rules_text:
        parts.append(
            _RULES_SECTION_TEMPLATE.format(rules_text=_cached_rules_text)
        )

    # Base scoring prompt with article details filled in.
    parts.append(
        _LLM_PROMPT_BASE.format(
            title=title,
            summary=summary or "No summary available.",
        )
    )

    return "".join(parts)


# ---------------------------------------------------------------------------
# In-memory dedup set (resets on restart; DB dedup on Server A is authoritative)
# ---------------------------------------------------------------------------
_seen_urls: set = set()
_MAX_SEEN_URLS = 10_000  # Cap to prevent unbounded memory growth


